// Fabriksbandet – inbyggda presets med ljud och mönster.
// Värden anges i parameterns egen enhet (Hz, s, steg, valets index …). Parametrar som inte nämns får sitt
// standardvärde. Mönster anges som text (se Monster.h); en rad på 16 steg upprepas till 64.
//
// Ordningen är menyns: Grund, EBM, New Beat, Industri och Demo. Från fas 4 följer presetsen samma plan för
// mönstren, så att man kan bygga en hel låt av vilket preset som helst:
//   mönster 1  gången – A och B växlar (B är variationen eller fyllningen)
//   mönster 2  refrängen eller kontrasten (en annan basgång, fler trummor)
//   mönster 3  intro eller utklingning (glesare)
//   mönster 4  trummorna: fyllning eller uppbyggnad inför nästa del
// En variant B som inte skrivs ut blir en kopia av A, så att A+B aldrig ger tysta takter. Vanliga presets har
// ingen låt; demopresetsen har en hel låt i låtläget.
//
