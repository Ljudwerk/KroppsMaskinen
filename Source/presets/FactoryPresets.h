struct TrumText
{
    int monster = 0, variant = 0;                            // 0-baserat mönster, 0 = A, 1 = B
    std::vector<std::pair<Trumma, const char*>> rader;
};

struct TonText
{
    Kanal kanal = Kanal::Kolvbasen;
    int monster = 0, variant = 0;
    const char* text = nullptr;
};

struct FactoryPreset
{
    const char* name;
    const char* category;
    std::vector<std::pair<juce::String, float>> values;
    std::vector<TrumText> trummor;
    std::vector<TonText> toner;
    const char* laten = nullptr;   // låten som text (se Laten.h); presets med låt slår på låtläget
};

// Ger varje mönster som bara har variant A en kopia som B.
inline std::vector<FactoryPreset> medVariantB (std::vector<FactoryPreset> lista)
{
    for (auto& f : lista)
    {
        const auto trummor = f.trummor;
        for (const auto& t : trummor)
            if (t.variant == 0 && std::none_of (trummor.begin(), trummor.end(),
                                                [&t] (const TrumText& b) { return b.monster == t.monster && b.variant == 1; }))
                f.trummor.push_back ({ t.monster, 1, t.rader });
        const auto toner = f.toner;
        for (const auto& t : toner)
            if (t.variant == 0 && std::none_of (toner.begin(), toner.end(),
                                                [&t] (const TonText& b) { return b.kanal == t.kanal && b.monster == t.monster && b.variant == 1; }))
                f.toner.push_back ({ t.kanal, t.monster, 1, t.text });
    }
    return lista;
}

